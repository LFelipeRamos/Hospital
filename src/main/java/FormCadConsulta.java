    private void btnCadastroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastroActionPerformed
        Medico medico = (Medico) cbMedico.getSelectedItem();
        Paciente paciente = (Paciente) cbPaciente.getSelectedItem();
        if (medico == null) { javax.swing.JOptionPane.showMessageDialog(this, "Selecione um médico."); return; }
        if (paciente == null) { javax.swing.JOptionPane.showMessageDialog(this, "Selecione um paciente."); return; }
        Consulta c = new Consulta();
        c.setMedico(medico);
        c.setPaciente(paciente);
        c.setData(inpDataConsulta.getText());
        c.setHora(inpHoraConsulta.getText());
        BDHospital.getInstance().inserirConsulta(c);
        javax.swing.JOptionPane.showMessageDialog(this, "Consulta cadastrada com sucesso!");
        cbMedico.setSelectedIndex(-1); cbPaciente.setSelectedIndex(-1); inpDataConsulta.setText(""); inpHoraConsulta.setText("");
    }//GEN-LAST:event_btnCadastroActionPerformed

