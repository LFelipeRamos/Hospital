    private void carregarCombos() {
        javax.swing.DefaultComboBoxModel<Medico> medModel = new javax.swing.DefaultComboBoxModel<>();
        for (Medico m : BDHospital.getInstance().listarMedicos()) {
            medModel.addElement(m);
        }
        cbMedico.setModel(medModel);
        cbMedico.setSelectedIndex(medModel.getSize() > 0 ? 0 : -1);

        javax.swing.DefaultComboBoxModel<Paciente> pacModel = new javax.swing.DefaultComboBoxModel<>();
        for (Paciente p : BDHospital.getInstance().listarPacientes()) {
            pacModel.addElement(p);
        }
        cbPaciente.setModel(pacModel);
        cbPaciente.setSelectedIndex(pacModel.getSize() > 0 ? 0 : -1);
    }
